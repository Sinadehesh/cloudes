import type { Cloud, CloudCategory, Weather } from '../core/types';

type Row = [
  id: string,
  commonName: string,
  scientificName: string,
  family: string,
  weather: Weather,
  aliases: string[],
  /** One direction is enough: look-alikes are matched both ways. */
  lookalikes: string[],
  fact: string,
];

function rows(category: CloudCategory, list: Row[]): Cloud[] {
  return list.map(([id, commonName, scientificName, family, weather, aliases, lookalikes, fact]) => ({
    id,
    commonName,
    scientificName,
    family,
    category,
    weather,
    aliases,
    lookalikes,
    fact,
  }));
}

