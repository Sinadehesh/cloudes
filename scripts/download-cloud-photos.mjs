#!/usr/bin/env node
// Downloads the curated cloud photos listed in scripts/cloud-photos.json (openly licensed Flickr
// photos found through Openverse), resizes them for the app bundle, and regenerates
// src/data/cloudImages.generated.ts with credits.
//
//   npm run photos:download             # fetch anything missing
//   npm run photos:download -- --force  # re-download and re-encode everything
//
// To add or swap photos, use `npm run photos:find -- <cloud-id>` and edit
// scripts/cloud-photos.json. Only CC0, Public Domain Mark, CC BY and CC BY-SA photos are allowed
// (no NC or ND: the app may be sold).

import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = join(root, 'assets/clouds');
const listPath = join(root, 'scripts/cloud-photos.json');
const generatedPath = join(root, 'src/data/cloudImages.generated.ts');

const LICENSE_LABEL = { CC0: 'CC0', PDM: 'Public domain', 'CC-BY': 'CC BY', 'CC-BY-SA': 'CC BY-SA' };
const MAX_SIDE = 1000;
const HEADERS = { 'User-Agent': 'CloudLock photo downloader (https://www.sinadehesh.com/app-lockers/)' };

const force = process.argv.includes('--force');
const list = JSON.parse(readFileSync(listPath, 'utf8'));
mkdirSync(outDir, { recursive: true });

async function download(url) {
  // Flickr's 1024 px ("_b") copy first; the 800 px ("_c") one if a photo has no large size.
  for (const candidate of [url, url.replace(/_b\.jpg$/, '_c.jpg')]) {
    const res = await fetch(candidate, { headers: HEADERS });
    if (res.ok) return Buffer.from(await res.arrayBuffer());
  }
  throw new Error(`could not download ${url}`);
}

const wanted = new Set();
let failures = 0;
for (const [cloudId, photos] of Object.entries(list)) {
  for (const [i, photo] of photos.entries()) {
    const file = `${cloudId}-${i + 1}.jpg`;
    wanted.add(file);
    if (!LICENSE_LABEL[photo.license]) {
      console.warn(`✗ ${file}: license ${photo.license} is not allowed`);
      failures++;
      continue;
    }
    if (!force && existsSync(join(outDir, file))) continue;
    try {
      const input = await download(photo.url);
      await sharp(input)
        .rotate()
        .resize(MAX_SIDE, MAX_SIDE, { fit: 'inside', withoutEnlargement: true })
        .jpeg({ quality: 74, mozjpeg: true })
        .toFile(join(outDir, file));
      console.log(`✓ ${file}`);
    } catch (err) {
      console.warn(`✗ ${file}: ${err.message}`);
      failures++;
    }
  }
}

// Drop photos that are no longer listed.
for (const file of readdirSync(outDir)) {
  if (file.endsWith('.jpg') && !wanted.has(file)) rmSync(join(outDir, file));
}

const lines = Object.entries(list)
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([cloudId, photos]) => {
    const items = photos
      .map((photo, i) => ({ photo, file: `${cloudId}-${i + 1}.jpg` }))
      .filter(({ file }) => existsSync(join(outDir, file)))
      .map(({ photo, file }) => {
        const credit = JSON.stringify({
          author: photo.author,
          license: LICENSE_LABEL[photo.license],
          sourceUrl: photo.sourceUrl,
        });
        return `    { source: require('../../assets/clouds/${file}'), credit: ${credit} },`;
      });
    return items.length ? `  ${JSON.stringify(cloudId)}: [\n${items.join('\n')}\n  ],` : null;
  })
  .filter(Boolean);

writeFileSync(
  generatedPath,
  `// Generated by scripts/download-cloud-photos.mjs — do not edit by hand.
// Photos: Flickr photographers via Openverse, CC0 / Public Domain Mark / CC BY / CC BY-SA.
// See scripts/cloud-photos.json.
import type { CloudImage } from './cloudImageTypes';

export const CLOUD_IMAGES: Record<string, CloudImage[]> = {
${lines.join('\n')}
};
`,
);
console.log(`Wrote ${generatedPath}`);
if (failures) {
  console.error(`${failures} photo(s) failed`);
  process.exit(1);
}
